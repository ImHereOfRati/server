#!/usr/bin/env node

// 부하 테스트용 테스트 데이터 생성
// 산출물 (기본 위치: loadtest/k6/generated/)
//   seed.sql     전용 MySQL에 적재할 INSERT 문. 유저 1,000명, 친구 관계 500건, 알림 20,000건. 앞부분에서 관련 table을 TRUNCATE 한다.
//   fixture.json 같은 데이터를 JSON으로 담은 것. issue-jwt.mjs가 토큰을 발급할 때, k6 시나리오가 요청 대상을 고를 때 읽는다.

import {mkdir, writeFile} from 'node:fs/promises';
import {randomUUID} from 'node:crypto';
import {fileURLToPath} from 'node:url';

const userCount = 1000;
const friendshipCount = 500;
const mutationPairCount = 0;
const notificationCount = 20000;
const defaultOutputDir = fileURLToPath(new URL('../generated', import.meta.url));
const outputDir = process.argv[2] ?? defaultOutputDir;

const users = Array.from({length: userCount}, (_, index) => ({
    id: randomUUID(),
    email: `loadtest-user-${index}@example.invalid`,
    nickname: `loadtest-${index}`,
    phone: `0109${String(index).padStart(7, '0')}`,
    fcmToken: `loadtest-fcm-token-${index}`,
}));

const relations = [];
const usedPairs = new Set();
for (let a = 0; a < userCount && relations.length < friendshipCount; a += 1) {
    for (let b = a + 1; b < userCount && relations.length < friendshipCount; b += 1) {
        const key = `${a}:${b}`;
        usedPairs.add(key);
        relations.push({id: randomUUID(), low: users[a].id, high: users[b].id});
    }
}

const mutationPairs = [];
for (let a = 0; a < userCount && mutationPairs.length < mutationPairCount; a += 1) {
    for (let b = a + 1; b < userCount && mutationPairs.length < mutationPairCount; b += 1) {
        const key = `${a}:${b}`;
        if (!usedPairs.has(key)) {
            usedPairs.add(key);
            mutationPairs.push({requester: users[a].id, receiver: users[b].id});
        }
    }
}

const q = (value) => `'${String(value).replaceAll("'", "''")}'`;
const now = 'NOW(6)';
const lines = [
    '-- Generated by loadtest/k6/init/generate-test-data.mjs',
    'SET FOREIGN_KEY_CHECKS = 0;',
    'TRUNCATE TABLE event_publication;',
    'TRUNCATE TABLE notification;',
    'TRUNCATE TABLE fcm_token;',
    'TRUNCATE TABLE friend_relations;',
    'TRUNCATE TABLE user_agreement;',
    'TRUNCATE TABLE users;',
    'SET FOREIGN_KEY_CHECKS = 1;',
    'START TRANSACTION;',
];

for (const user of users) {
    lines.push(`INSERT INTO users (id, email, nickname, role, provider, status, oidc_subject, refresh_token_version,
                                   created_at, updated_at)
                VALUES (UUID_TO_BIN(${q(user.id)}), ${q(user.email)}, ${q(user.nickname)}, 'NORMAL', 'GOOGLE', 'ACTIVE',
                        ${q(`loadtest-${user.id}`)}, 0, ${now}, ${now});`);
    lines.push(`INSERT INTO fcm_token (token, owner_id, device_type, created_at, updated_at)
                VALUES (${q(user.fcmToken)}, UUID_TO_BIN(${q(user.id)}), 'AOS', ${now}, ${now});`);
}

for (const relation of relations) {
    lines.push(`INSERT INTO friend_relations (friend_relation_id, low_user_id, high_user_id, status, initiated_user_id,
                                              message, low_alias, high_alias, created_at, updated_at)
                VALUES (UUID_TO_BIN(${q(relation.id)}), UUID_TO_BIN(${q(relation.low)}),
                        UUID_TO_BIN(${q(relation.high)}), 'ACCEPTED', UUID_TO_BIN(${q(relation.low)}),
                        ${q('fixture friendship')}, NULL, NULL, ${now}, ${now});`);
}

for (let index = 0; index < notificationCount; index += 1) {
    const recipient = users[index % userCount];
    lines.push(`INSERT INTO notification (dedupe_key, target_identifier, method, sender_alias, type, title, body,
                                          extra_data, status, attempts, is_read, created_at, updated_at)
                VALUES (${q(`loadtest-notification-${index}`)}, ${q(recipient.id)}, 'FCM', 'loadtest', 'ARRIVAL',
                        'loadtest', 'loadtest notification', '{}', 'SENT', 1, b'0', ${now}, ${now});`);
}

lines.push('COMMIT;');
await mkdir(outputDir, {recursive: true});
await writeFile(`${outputDir}/seed.sql`, `${lines.join('\n')}\n`, 'utf8');
await writeFile(`${outputDir}/fixture.json`, JSON.stringify({users, relations, mutationPairs}, null, 2), 'utf8');
console.log(`Generated ${users.length} users, ${relations.length} friendships, ${notificationCount} notifications in ${outputDir}`);
